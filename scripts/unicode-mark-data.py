"""Generate the glyph atlas combining-mark table from Unicode 17.0.0.

Usage: unicode-mark-data.py DIRECTORY containing DerivedGeneralCategory.txt
from https://www.unicode.org/Public/17.0.0/ucd/extracted/. Standard library
only. Writes src/atlas/marks.rs (General_Category Mn and Me, less the
variation selectors the atlas classifies separately) and the fixture
tests/fixtures/unicode-marks/marks.txt (every Mn and Me range), then run
`cargo fmt`.
"""
from pathlib import Path
import hashlib
import sys

ROOT = Path(__file__).resolve().parent.parent
NAME = 'DerivedGeneralCategory.txt'
PIN = 'd62e5bab70ca74f099343f71224fa051cb1fdd61a1ab45c0488c44cfc0b6102e'
VARIATION_SELECTORS = set(range(0xFE00, 0xFE10)) | set(range(0xE0100, 0xE01F0))


def ranges(values):
    out = []
    for cp, value in sorted(values.items()):
        if out and out[-1][1] + 1 == cp and out[-1][2] == value:
            out[-1] = (out[-1][0], cp, value)
        else:
            out.append((cp, cp, value))
    return out


def main():
    path = Path(sys.argv[1]) / NAME
    if hashlib.sha256(path.read_bytes()).hexdigest() != PIN:
        raise ValueError(f'{NAME}: the pinned Unicode 17.0.0 file is required')
    marks = {}
    for line in path.read_text().splitlines():
        fields = line.split('#')[0].strip().split(';')
        if len(fields) < 2 or fields[1].strip() not in ('Mn', 'Me'):
            continue
        ends = fields[0].strip().split('..')
        for cp in range(int(ends[0], 16), int(ends[-1], 16) + 1):
            marks[cp] = fields[1].strip()
    header = [
        '// SPDX-License-Identifier: GPL-3.0-only',
        '// Generated by scripts/unicode-mark-data.py; Unicode 17.0.0.',
        '// Do not edit by hand.',
        '// Copyright Unicode, Inc.; tests/fixtures/unicode-marks/LICENSE-UNICODE.txt.',
        f'// {NAME} SHA-256: {PIN}',
        '//! General_Category Mn and Me ranges, less the variation selectors.',
        '',
        'pub(super) const COMBINING_MARKS: &[(u32, u32)] = &[',
    ]
    atlas = {cp: 'M' for cp in marks if cp not in VARIATION_SELECTORS}
    header += [f'    (0x{start:x}, 0x{end:x}),' for start, end, _ in ranges(atlas)]
    header.append('];')
    (ROOT / 'src/atlas/marks.rs').write_text('\n'.join(header) + '\n')
    fixture = [
        '# Unicode 17.0.0 General_Category Mn and Me ranges; Unicode-3.0, see LICENSE-UNICODE.txt.',
        '# Generated by scripts/unicode-mark-data.py.',
        f'# {NAME} SHA-256: {PIN}',
    ]
    for start, end, value in ranges(marks):
        span = f'{start:04X}' if start == end else f'{start:04X}..{end:04X}'
        fixture.append(f'{span};{value}')
    (ROOT / 'tests/fixtures/unicode-marks/marks.txt').write_text('\n'.join(fixture) + '\n')


if __name__ == '__main__':
    main()
