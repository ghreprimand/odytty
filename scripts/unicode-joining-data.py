"""Generate the joining-script tables for contextual joining runs from Unicode 17.0.0.

Usage: unicode-joining-data.py <directory holding Scripts.txt, UnicodeData.txt,
and DerivedJoiningType.txt>. Inputs:
https://www.unicode.org/Public/17.0.0/ucd/Scripts.txt,
https://www.unicode.org/Public/17.0.0/ucd/UnicodeData.txt, and
https://www.unicode.org/Public/17.0.0/ucd/extracted/DerivedJoiningType.txt.
Standard library only.

For each contextual joining script other than Arabic (Arabic keeps its own
tables), two tables of (first, last, script id) ranges: the joining letters
(Joining_Type D, R, L, or C, of that script) and the transparent marks
(Joining_Type T and General_Category Mn, of that script) that may ride a
letter inside its run.
"""
from pathlib import Path
import hashlib
import sys

ROOT = Path(__file__).resolve().parent.parent
SCRIPTS = ('Syriac', 'Nko', 'Mandaic', 'Adlam', 'Hanifi_Rohingya', 'Mongolian')


def properties(path, field=1):
    out = {}
    for line in path.read_text(encoding='utf-8').splitlines():
        fields = line.split('#')[0].strip().split(';')
        if len(fields) <= field:
            continue
        ends = fields[0].strip().split('..')
        start, end = int(ends[0], 16), int(ends[-1], 16)
        out.update((cp, fields[field].strip()) for cp in range(start, end + 1))
    return out


def categories(path):
    out = {}
    first = None
    for line in path.read_text(encoding='utf-8').splitlines():
        fields = line.split(';')
        cp, name, category = int(fields[0], 16), fields[1], fields[2]
        if name.endswith(', First>'):
            first = cp
            continue
        if name.endswith(', Last>'):
            out.update((c, category) for c in range(first, cp + 1))
            continue
        out[cp] = category
    return out


def ranges(values):
    out = []
    for cp, value in sorted(values.items()):
        if out and out[-1][1] + 1 == cp and out[-1][2] == value:
            out[-1] = (out[-1][0], cp, value)
        else:
            out.append((cp, cp, value))
    return out


def main():
    folder = Path(sys.argv[1])
    sources = [folder / 'Scripts.txt', folder / 'UnicodeData.txt',
               folder / 'DerivedJoiningType.txt']
    for source in (sources[0], sources[2]):
        if '17.0.0' not in source.read_text(encoding='utf-8').splitlines()[0]:
            raise ValueError(f'{source.name}: Unicode 17.0.0 is required')
    scripts = properties(sources[0])
    category = categories(sources[1])
    joining = properties(sources[2])
    missing = set(SCRIPTS) - set(scripts.values())
    if missing:
        raise ValueError(f'unknown script names: {sorted(missing)}')
    ids = {name: i + 1 for i, name in enumerate(SCRIPTS)}
    letters = {cp: ids[s] for cp, s in scripts.items()
               if s in ids and joining.get(cp) in ('D', 'R', 'L', 'C')}
    marks = {cp: ids[s] for cp, s in scripts.items()
             if s in ids and joining.get(cp) == 'T' and category.get(cp) == 'Mn'}
    text = ['// SPDX-License-Identifier: GPL-3.0-only',
            '// Generated by scripts/unicode-joining-data.py; Unicode 17.0.0.',
            '// Do not edit by hand.',
            '// Copyright Unicode, Inc.; tests/fixtures/unicode-indic/LICENSE-UNICODE.txt.',
            *(f'// {source.name} SHA-256: {hashlib.sha256(source.read_bytes()).hexdigest()}'
              for source in sources),
            '// Script ids: ' + ', '.join(f'{ids[name]} {name}' for name in SCRIPTS) + '.',
            '',
            '/// Joining letters (Joining_Type D, R, L, or C) by script id.',
            'pub(super) const JOINING_LETTERS: &[(u32, u32, u8)] = &[']
    text.extend(f'    (0x{a:x}, 0x{b:x}, {sid}),' for a, b, sid in ranges(letters))
    text += ['];', '',
             '/// Transparent nonspacing marks (Joining_Type T, General_Category Mn) by',
             '/// script id.',
             'pub(super) const JOINING_MARKS: &[(u32, u32, u8)] = &[']
    text.extend(f'    (0x{a:x}, 0x{b:x}, {sid}),' for a, b, sid in ranges(marks))
    text.append('];')
    (ROOT / 'src/ligature/joining_data.rs').write_text('\n'.join(text) + '\n', encoding='utf-8', newline='\n')
    print(f'{len(letters)} letters, {len(marks)} marks')


if __name__ == '__main__':
    main()
