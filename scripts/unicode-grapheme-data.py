"""Generate the Unicode 17.0.0 grapheme property table and conformance fixture.

Usage: unicode-grapheme-data.py DIRECTORY holding GraphemeBreakProperty.txt,
GraphemeBreakTest.txt (both from https://www.unicode.org/Public/17.0.0/ucd/auxiliary/),
DerivedCoreProperties.txt (ucd/), and emoji-data.txt (ucd/emoji/).
Standard library only. Every input must match its pinned SHA-256.

Writes src/core/grapheme/data.rs (one sorted range table of packed property
bytes) and tests/fixtures/unicode-grapheme/GraphemeBreakTest-17.0.0.txt (the
whole conformance file, byte for byte). Run `cargo fmt` afterwards.
"""
from pathlib import Path
import hashlib
import sys

ROOT = Path(__file__).resolve().parent.parent
PINS = {
    'GraphemeBreakProperty.txt': 'd6b51d1d2ae5c33b451b7ed994b48f1f4dc62b2272a5831e7fd418514a6bae89',
    'GraphemeBreakTest.txt': 'e2d134d2c52919bace503ebb6a551c1855fe1a1faec18478c78fff254a1793ec',
    'DerivedCoreProperties.txt': '24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08',
    'emoji-data.txt': '2cb2bb9455cda83e8481541ecf5b6dfda66a3bb89efa3fa7c5297eccf607b72b',
}
# Low four bits of a packed byte; must match `Class` in src/core/grapheme/mod.rs.
CLASSES = ['Other', 'CR', 'LF', 'Control', 'Extend', 'ZWJ', 'Regional_Indicator',
           'Prepend', 'SpacingMark', 'L', 'V', 'T', 'LV', 'LVT']
PICT = 0x10
INCB = {'Linker': 0x20, 'Consonant': 0x40, 'Extend': 0x60}


def rows(path):
    for line in path.read_text(encoding='utf-8').splitlines():
        fields = [f.strip() for f in line.split('#')[0].split(';')]
        if len(fields) < 2:
            continue
        ends = fields[0].split('..')
        yield int(ends[0], 16), int(ends[-1], 16), fields[1:]


def main():
    source = Path(sys.argv[1])
    for name, sha in PINS.items():
        if hashlib.sha256((source / name).read_bytes()).hexdigest() != sha:
            raise ValueError(f'{name}: the pinned Unicode 17.0.0 file is required')
    packed = {}
    for start, end, fields in rows(source / 'GraphemeBreakProperty.txt'):
        for cp in range(start, end + 1):
            assert cp not in packed, f'{cp:04X}: two grapheme classes'
            packed[cp] = CLASSES.index(fields[0])
    for start, end, fields in rows(source / 'emoji-data.txt'):
        if fields[0] == 'Extended_Pictographic':
            for cp in range(start, end + 1):
                packed[cp] = packed.get(cp, 0) | PICT
    for start, end, fields in rows(source / 'DerivedCoreProperties.txt'):
        if fields[0] == 'InCB':
            for cp in range(start, end + 1):
                assert packed.get(cp, 0) & 0x60 == 0
                packed[cp] = packed.get(cp, 0) | INCB[fields[1]]
    table = []
    for cp, value in sorted(packed.items()):
        if value == 0:
            continue
        if table and table[-1][1] + 1 == cp and table[-1][2] == value:
            table[-1] = (table[-1][0], cp, value)
        else:
            table.append((cp, cp, value))
    out = ['// SPDX-License-Identifier: GPL-3.0-only',
           '// Generated by scripts/unicode-grapheme-data.py; Unicode 17.0.0.',
           '// Do not edit by hand.',
           '// Copyright Unicode, Inc.; tests/fixtures/unicode-grapheme/LICENSE-UNICODE.txt.']
    out += [f'// {name} SHA-256: {sha}' for name, sha in PINS.items()]
    out.append('// Packed byte: low four bits grapheme class, 0x10 Extended_Pictographic,')
    out.append('// bits 0x60 InCB (0x20 Linker, 0x40 Consonant, 0x60 Extend).')
    out.append('pub(super) const PROPERTIES: &[(u32, u32, u8)] = &[')
    out.extend(f'    (0x{a:x}, 0x{b:x}, 0x{v:02x}),' for a, b, v in table)
    out.append('];')
    (ROOT / 'src/core/grapheme/data.rs').write_text('\n'.join(out) + '\n', encoding='utf-8', newline='\n')
    fixture = ROOT / 'tests/fixtures/unicode-grapheme'
    fixture.mkdir(parents=True, exist_ok=True)
    (fixture / 'GraphemeBreakTest-17.0.0.txt').write_bytes((source / 'GraphemeBreakTest.txt').read_bytes())


if __name__ == '__main__':
    main()
