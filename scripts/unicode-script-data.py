"""Generate the script table for general owner shaping from Unicode 17.0.0.

Usage: unicode-script-data.py <directory holding Scripts.txt>. Input:
https://www.unicode.org/Public/17.0.0/ucd/Scripts.txt. Standard library only.

Every script is listed except the ones whose owners keep another path: the
tuned shaping groups (their own eligibility rules), Latin, Greek, Cyrillic,
and Common (the per-cell mark path), Arabic and the contextual joining scripts
(the joining overlay), and Han, Hiragana, and Katakana (precomposed single
scalars). Inherited is listed with id 0: it may ride a base, never lead one.
"""
from pathlib import Path
import hashlib
import sys
import textwrap

ROOT = Path(__file__).resolve().parent.parent
TUNED = ('Devanagari', 'Bengali', 'Gurmukhi', 'Gujarati', 'Oriya', 'Tamil',
         'Telugu', 'Kannada', 'Malayalam', 'Sinhala', 'Khmer', 'Myanmar',
         'Thai', 'Lao', 'Tibetan', 'Chakma', 'Javanese', 'Grantha', 'Tai_Tham')
OTHER_PATHS = ('Latin', 'Greek', 'Cyrillic', 'Common', 'Arabic', 'Syriac',
               'Nko', 'Mongolian', 'Adlam', 'Hanifi_Rohingya', 'Mandaic',
               'Han', 'Hiragana', 'Katakana')


def properties(path):
    out = {}
    for line in path.read_text(encoding='utf-8').splitlines():
        fields = line.split('#')[0].strip().split(';')
        if len(fields) < 2:
            continue
        ends = fields[0].strip().split('..')
        start, end = int(ends[0], 16), int(ends[-1], 16)
        out.update((cp, fields[1].strip()) for cp in range(start, end + 1))
    return out


def ranges(values):
    out = []
    for cp, value in sorted(values.items()):
        if out and out[-1][1] + 1 == cp and out[-1][2] == value:
            out[-1] = (out[-1][0], cp, value)
        else:
            out.append((cp, cp, value))
    return out


def main():
    source = Path(sys.argv[1]) / 'Scripts.txt'
    if '17.0.0' not in source.read_text(encoding='utf-8').splitlines()[0]:
        raise ValueError('Scripts.txt: Unicode 17.0.0 is required')
    scripts = properties(source)
    names = set(scripts.values())
    missing = (set(TUNED) | set(OTHER_PATHS) | {'Inherited'}) - names
    if missing:
        raise ValueError(f'unknown script names: {sorted(missing)}')
    general = sorted(names - set(TUNED) - set(OTHER_PATHS) - {'Inherited'})
    ids = {name: i + 1 for i, name in enumerate(general)}
    ids['Inherited'] = 0
    if len(general) > 255:
        raise ValueError('script ids no longer fit in u8')
    values = {cp: ids[script] for cp, script in scripts.items() if script in ids}
    table = ranges(values)
    if any(start < 0x80 for start, _, _ in table):
        raise ValueError('the general table must exclude ASCII')
    text = ['// SPDX-License-Identifier: GPL-3.0-only',
            '// Generated by scripts/unicode-script-data.py; Unicode 17.0.0.',
            '// Do not edit by hand.',
            '// Copyright Unicode, Inc.; tests/fixtures/unicode-indic/LICENSE-UNICODE.txt.',
            f'// Scripts.txt SHA-256: {hashlib.sha256(source.read_bytes()).hexdigest()}',
            # A no-break space keeps each id beside its name while wrapping.
            *(line.replace('\u00a0', ' ') for line in textwrap.wrap(
                'Script ids: 0\u00a0Inherited, ' + ', '.join(f'{ids[name]}\u00a0{name}' for name in general) + '.',
                width=97, initial_indent='// ', subsequent_indent='// ', break_on_hyphens=False)),
            'pub(super) const GENERAL_SCRIPTS: &[(u32, u32, u8)] = &[']
    text.extend(f'    (0x{a:x}, 0x{b:x}, {sid}),' for a, b, sid in table)
    text.append('];')
    (ROOT / 'src/complex_shaping/script_data.rs').write_text('\n'.join(text) + '\n', encoding='utf-8', newline='\n')
    print(f'{len(general)} scripts, {len(table)} ranges')


if __name__ == '__main__':
    main()
